// WriteMate AI — Electron main process.
//
// Phase A: wraps the existing Express server + public/ frontend (the same
// code the browser-tab workflow uses) in a native window, so every feature
// that already works in a browser tab works identically here.
// Phase B: also spawns the bundled AutoHotkey interpreter +
// WriteMate-Hotkey.ahk as a child process, tied to the app's own open/quit
// lifecycle — Ctrl+Alt+W now works whenever this app is running, with no
// separate AutoHotkey install and no relaunching the script by hand after
// every reboot.
// Phase C: exposes exactly two safe actions to the page via a preload
// script + contextBridge — opening the bundled browser-extension folder in
// the system file manager, and reading its path — so the app can show a
// "load the extension" helper without loosening the sandboxed window's
// security posture from Phase A.
// Phase D (this update): resolves AHK_DIR/EXTENSION_DIR from
// process.resourcesPath when running as a packaged (installed) app instead
// of the dev-mode project-relative paths — see electron-builder's
// `extraResources` in package.json. API-key encryption at rest (via
// Electron's safeStorage) lives in server/lib/secretStorage.js, transparent
// to this file since it's wired into server/lib/store.js instead.
//
// Requires Electron 28+ (for ESM main-process support, since this project
// is "type": "module" — see package.json).

import { app, BrowserWindow, ipcMain, shell } from 'electron';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// Original icon (no Grammarly/third-party assets) generated by
// scripts/gen-icon.py — see build/icon-1024.png for the source render.
const ICON_PATH = path.join(__dirname, '..', 'build', 'icon.ico');

// Bundled AutoHotkey v2 interpreter + the hotkey script it runs (Phase B),
// and the bundled browser extension folder (Phase C). In dev (`npm run
// electron`) these are plain project-relative folders. In a packaged build
// (Phase D), electron-builder's `extraResources` (see package.json's
// "build" block) copies them into the installed app's own resources folder
// instead, at `process.resourcesPath/ahk` and `process.resourcesPath/
// extension` — `app.isPackaged` is Electron's own reliable way to tell
// which situation we're in, rather than guessing from argv or __dirname.
const AHK_DIR = app.isPackaged
  ? path.join(process.resourcesPath, 'ahk')
  : path.join(__dirname, '..', 'resources', 'ahk');
const AHK_EXE = path.join(AHK_DIR, 'AutoHotkey64.exe');
const AHK_SCRIPT = path.join(AHK_DIR, 'WriteMate-Hotkey.ahk');

const EXTENSION_DIR = app.isPackaged
  ? path.join(process.resourcesPath, 'extension')
  : path.join(__dirname, '..', 'browser-extension');
const PRELOAD_PATH = path.join(__dirname, 'preload.cjs');

// Controls the folder name Electron uses for app.getPath('userData') (e.g.
// %APPDATA%\WriteMate AI\ on Windows, instead of the less friendly
// %APPDATA%\writemate-ai\ it would otherwise derive from package.json's
// "name" field). Must be set before any app.getPath() call.
app.setName('WriteMate AI');

// IMPORTANT: this must run BEFORE server/lib/store.js is first imported
// (via the startServer import below), because store.js reads
// WRITEMATE_DATA_DIR at module-load time to decide where to keep
// settings.json/history.json/etc. A packaged app's install folder is often
// read-only (e.g. under "Program Files"), and even when it isn't, mixing
// user data into the install folder is bad practice — so the Electron
// build always keeps its data in the OS's standard per-user app-data
// location instead, separate from the `./data` folder that `npm run dev`
// (running the server directly, outside Electron) still uses.
process.env.WRITEMATE_DATA_DIR = path.join(app.getPath('userData'), 'data');

const { startServer } = await import('../server/index.js');

/** @type {import('http').Server | null} */
let httpServer = null;
let serverPort = 4173;

/** @type {import('child_process').ChildProcess | null} */
let hotkeyProcess = null;

function startHotkeyBridge() {
  // Windows-only feature (AutoHotkey itself is Windows-only); silently skip
  // elsewhere rather than erroring, so this doesn't block Phase-A behavior
  // on other platforms.
  if (process.platform !== 'win32') return;

  if (!fs.existsSync(AHK_EXE) || !fs.existsSync(AHK_SCRIPT)) {
    console.warn(
      `Hotkey bridge disabled: expected AutoHotkey64.exe + WriteMate-Hotkey.ahk under ${AHK_DIR}`
    );
    return;
  }

  hotkeyProcess = spawn(AHK_EXE, [AHK_SCRIPT], {
    windowsHide: true, // no console/tray flash on launch
    stdio: 'ignore', // nothing sensitive is written to stdout/stderr, but no need to keep pipes open either
  });

  hotkeyProcess.on('error', (err) => {
    // e.g. AHK_EXE missing/corrupted, or blocked by AV — app still runs
    // fine without the hotkey, so this is a warning, not a crash.
    console.error('Hotkey bridge failed to start:', err.message);
    hotkeyProcess = null;
  });

  hotkeyProcess.on('exit', (code) => {
    // AHK exiting on its own (e.g. user quit it from the tray icon) isn't
    // an app-level failure — just note it and clear the handle so
    // before-quit doesn't try to kill an already-dead process.
    if (code !== 0 && code !== null) {
      console.warn(`Hotkey bridge exited unexpectedly (code ${code})`);
    }
    hotkeyProcess = null;
  });
}

function stopHotkeyBridge() {
  if (hotkeyProcess && !hotkeyProcess.killed) {
    hotkeyProcess.kill();
  }
  hotkeyProcess = null;
}

// Phase C: handlers for the two functions preload.cjs exposes to the page.
// shell.openPath opens the folder in the OS's native file manager (Windows
// Explorer) — this is as far as Electron can automate the "load unpacked"
// extension flow; it cannot drive Chrome's own chrome://extensions page,
// which is a browser-internal URL, not something an external app can open
// or script (see packaging-plan.md's browser-extension-install decision).
ipcMain.handle('get-extension-folder-path', () => EXTENSION_DIR);
ipcMain.handle('open-extension-folder', () => shell.openPath(EXTENSION_DIR));

function waitForListening(server) {
  return new Promise((resolve, reject) => {
    server.once('listening', resolve);
    server.once('error', reject);
  });
}

async function createWindow() {
  const win = new BrowserWindow({
    width: 1280,
    height: 860,
    minWidth: 860,
    minHeight: 600,
    title: 'WriteMate AI',
    icon: ICON_PATH,
    autoHideMenuBar: true,
    webPreferences: {
      // Phase A needed no preload script at all — the window just loaded
      // the same local HTTP page a browser tab would, with zero
      // Node/Electron APIs exposed to it. Phase C adds exactly one:
      // preload.cjs exposes two narrow functions (open/read the bundled
      // extension folder) via contextBridge — contextIsolation/sandbox
      // stay on, nodeIntegration stays off, so the page still has no
      // direct Node access.
      preload: PRELOAD_PATH,
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });

  await win.loadURL(`http://127.0.0.1:${serverPort}`);
  return win;
}

app.whenReady().then(async () => {
  const { server, port } = startServer();
  httpServer = server;
  serverPort = port;
  await waitForListening(server);

  await createWindow();
  startHotkeyBridge();

  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) createWindow();
  });
});

app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') app.quit();
});

app.on('before-quit', () => {
  if (httpServer) httpServer.close();
  stopHotkeyBridge();
});
